#!/usr/bin/env python3
"""
CLI tool to detect performance regressions by conmparing two JSON
files generated by pytest-benchmark (--benchmark-json=output.json).

Usage:
  # Compare two local files
  python check_benchmarks.py output_master.json output_new.json

  # Compare against gh-pages (automatic download)
  python check_benchmarks.py output.json --threshold=1.5

  # Change the regression threshold (por defecto 1.5 = 150% más lento)
  python check_benchmarks.py output_new.json --threshold=2.0

Output:
  - Output code 0: no significative regressions.
  - Output code 1: some regressions was detected (with messages in stdout)
"""

import argparse
import json
import sys
from pathlib import Path


def load_benchmarks(json_path):
    """Load the JSON benchmark file and return a dict {nombre: ops}."""
    with open(json_path, "r") as f:
        data = json.load(f)

    benchmarks = {}
    for b in data.get("benchmarks", []):
        name = b.get("fullname") or b.get("name")
        # Usamos OPS (operaciones por segundo) como métrica principal
        ops = b.get("stats", {}).get("ops")
        if name and ops is not None:
            benchmarks[name] = ops
    return benchmarks


def get_baseline_from_gh_pages():
    """Try to download the last data.js from gh-pages and extract the benchmarks."""
    import requests

    url = (
        "https://raw.githubusercontent.com/Mathics3/mathics-core/gh-pages/cache/data.js"
    )
    try:
        resp = requests.get(url, timeout=10)
        if resp.status_code == 200:
            content = resp.text
            if content.startswith("window.BENCHMARK_DATA = "):
                json_str = content[len("window.BENCHMARK_DATA = ") :]
                data = json.loads(json_str)
                # The structure of data.js is slightly different...:
                # { commit: {...}, date: ..., tool: 'pytest', benches: [...] }
                benchmarks_data_list = data["entries"]["Mathics3 Core Benchmarks"]
                data = benchmarks_data_list[-1]
                if "benches" in data:
                    # Convert to the pytest-benchmark format
                    benchmarks = {}
                    for b in data["benches"]:
                        name = b.get("name")
                        value = b.get("value")  # Already ops
                        if name and value is not None:
                            benchmarks[name] = value
                    return benchmarks
    except Exception as e:
        print("exception e", json_str)
        print(f"⚠️ Baseline could not be download from gh-pages: {e}", file=sys.stderr)
    return None


def get_baseline_from_local(baseline_path):
    """Load the baseline from a local JSON file."""
    if not Path(baseline_path).exists():
        return None
    return load_benchmarks(baseline_path)


def compare_benchmarks(current, baseline, threshold):
    """Compare two benchmark dicts and return a list of regressions."""
    regressions = []
    improvements = []

    for name, cur_ops in current.items():
        base_ops = baseline.get(name)
        if base_ops is None:
            continue  # new benchmark, cannot be compared.

        # Ratio = base / current; >1 means current is slower than the reference.
        ratio = base_ops / cur_ops if cur_ops > 0 else float("inf")
        if ratio > threshold:
            regressions.append((name, cur_ops, base_ops, ratio))
        elif ratio < 0.8:  # opcional: also show improvements.
            improvements.append((name, cur_ops, base_ops, ratio))

    return regressions, improvements


def main():
    parser = argparse.ArgumentParser(
        description="Detect performance regressions comparing two JSON files from pytest-benchmark."
    )
    parser.add_argument(
        "current",
        nargs="?",
        default="output.json",
        help="JSON file with the benchmarks on the current branch (by default: output.json)",
    )
    parser.add_argument(
        "baseline", nargs="?", help="JSON file with the baseline results (opcional)"
    )
    parser.add_argument(
        "--threshold",
        type=float,
        default=1.5,
        help="Regression threshold (ratio). Default= 1.5 (150%% slower)",
    )
    parser.add_argument(
        "--baseline-from-gh",
        action="store_true",
        help="Dowload the baseline from gh-pages",
    )
    parser.add_argument(
        "--quiet",
        action="store_true",
        help="Do not show details. Just generate the output code.",
    )

    args = parser.parse_args()

    # 1. Load the current results
    try:
        current = load_benchmarks(args.current)
    except FileNotFoundError:
        print(f"❌ File not found: {args.current}", file=sys.stderr)
        sys.exit(2)
    except Exception as e:
        print(f"❌ Error loading {args.current}: {e}", file=sys.stderr)
        sys.exit(2)

    if not current:
        print("⚠️ Benchmarks not found for the current file.", file=sys.stderr)
        sys.exit(2)

    # 2. Get the baseline
    baseline = None
    if args.baseline_from_gh:
        baseline = get_baseline_from_gh_pages()
        if baseline is None:
            print("❌ Baseline from gh-pages not available.", file=sys.stderr)
            sys.exit(2)
    elif args.baseline:
        try:
            baseline = get_baseline_from_local(args.baseline)
        except Exception as e:
            print(f"❌ Error loading baseline {args.baseline}: {e}", file=sys.stderr)
            sys.exit(2)
    else:
        # If baseline is not specified, try to load it from gh-pages automatically
        baseline = get_baseline_from_gh_pages()
        if baseline is None:
            print(
                "⚠️ Baseline not found locally or in gh-pages. Using just the current result.",
                file=sys.stderr,
            )
            sys.exit(0)

    # 3. Comparing
    regressions, improvements = compare_benchmarks(current, baseline, args.threshold)

    # 4. Show results
    if not args.quiet:
        print(f"📊 Comparing {len(current)} benchmarks...")
        print(
            f"   Thresold: {args.threshold}x (regression if ratio > {args.threshold})"
        )
        print()

    if regressions:
        if not args.quiet:
            print("::error::⚠️ REGRESSIONS DETECTED:")
            for name, cur, base, ratio in sorted(
                regressions, key=lambda x: x[3], reverse=True
            ):
                # Show just the short name (not the complete path)
                short_name = name.split("::")[-1] if "::" in name else name
                print(f"  ❌ {short_name}")
                print(
                    f"     Actual: {cur:.2f} ops/sec | Base: {base:.2f} ops/sec | Ratio: {ratio:.2f}x"
                )
        sys.exit(1)
    else:
        if not args.quiet:
            print("✅ Significant regressions were not detected.")
            if improvements:
                print(f"   Detected improvements: {len(improvements)} benchmarks")
                # Best 3 improvements
                for name, cur, base, ratio in sorted(improvements, key=lambda x: x[3])[
                    :3
                ]:
                    short_name = name.split("::")[-1] if "::" in name else name
                    print(
                        f"  🚀 {short_name}: {cur:.2f} vs {base:.2f} (ratio {ratio:.2f})"
                    )
        sys.exit(0)


if __name__ == "__main__":
    main()
